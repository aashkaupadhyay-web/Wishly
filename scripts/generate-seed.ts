import { writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
import { CATALOG } from "../src/data/catalog";

const q = (v: string | null) => (v === null ? "null" : `'${v.replace(/'/g, "''")}'`);
const cols = [
  "id", "name", "retailer", "product_url", "image_url", "category", "subcategory", "color",
  "material", "style", "silhouette", "hardware", "closure", "size", "shape", "description",
] as const;

const rows = CATALOG.map((p) => `  (${cols.map((c) => q((p as unknown as Record<string, string | null>)[c] ?? null)).join(", ")})`);

const sql = `-- GENERATED by \`npm run seed:sql\` from src/data/catalog.ts. Do not edit by hand.
-- Idempotent: safe to run repeatedly.
insert into public.catalog_products (${cols.join(", ")}) values
${rows.join(",\n")}
on conflict (id) do update set
${cols.filter((c) => c !== "id").map((c) => `  ${c} = excluded.${c}`).join(",\n")};
`;

const out = path.resolve(__dirname, "../supabase/seed.sql");
mkdirSync(path.dirname(out), { recursive: true });
writeFileSync(out, sql);
console.log(`Wrote ${CATALOG.length} catalog rows to ${out}`);
